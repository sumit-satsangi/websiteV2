import { mkdir, readFile, writeFile } from "node:fs/promises";

const readJson = async (file) => JSON.parse(await readFile(file, "utf8"));
const projects = await readJson("content/projects.json");
const blogs = await readJson("content/blogs.json");
const podcasts = await readJson("content/podcasts.json");
const podcastShow = await readJson("content/podcast-show.json");

const generated = `// Generated by scripts/generate-content.mjs. Edit files in /content instead.\nexport const rawProjects = ${JSON.stringify(projects, null, 2)} as const;\nexport const rawBlogs = ${JSON.stringify(blogs, null, 2)} as const;\nexport const rawPodcastEpisodes = ${JSON.stringify(podcasts, null, 2)} as const;\nexport const rawPodcastShow = ${JSON.stringify(podcastShow, null, 2)} as const;\n`;

await mkdir("client/src/data", { recursive: true });
await writeFile("client/src/data/generatedContent.ts", generated);
console.log(`Generated content adapter: ${projects.length} projects, ${blogs.length} blogs, ${podcasts.length} podcast episodes`);
